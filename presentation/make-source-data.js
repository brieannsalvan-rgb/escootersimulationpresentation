/* =====================================================================
   make-source-data.js
   Copies the analyzer's source files (from the sibling folder "project")
   into source-data.js, so that presentation.html can show the real code
   even when it is opened by double-clicking (browsers block reading
   local files directly).

   Run again (in this folder) after you change any code in "project":
       node make-source-data.js
   ===================================================================== */
const fs = require("fs");
const path = require("path");

const PROJECT_DIR = path.join(__dirname, "..", "project");
const FILES = ["script.js", "index.html", "style.css"];

const data = {};
FILES.forEach(f => { data[f] = fs.readFileSync(path.join(PROJECT_DIR, f), "utf8"); });

const out =
  "/* Generated by make-source-data.js - copy of the project source for presentation.html */\n" +
  "window.SOURCE_FILES = " + JSON.stringify(data) + ";\n";

fs.writeFileSync(path.join(__dirname, "source-data.js"), out, "utf8");
console.log("source-data.js written (" + FILES.length + " files from ../project).");
